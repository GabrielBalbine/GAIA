@st.cache_data(ttl=300)
def compute_metrics(json_path: str) -> dict:
    frames = load_json_data(json_path)
    if not frames:
        return {"total_frames": 0}

    total = len(frames)
    g_looking = c_looking = mutual = id_locked_count = 0
    g_scores, c_scores, g_confs, c_confs = [], [], [], []
    g_fit_scores, c_fit_scores = [], []
    g_det_confs, c_det_confs = [], []
    g_human_scores, c_human_scores = [], []
    shoulder_tilts_g, shoulder_tilts_c = [], []
    torso_heights_g, torso_heights_c = [], []
    hand_distances_g, hand_distances_c = [], []
    head_distances = []

    for frame in frames:
        if frame.get("mutual_attention", False):
            mutual += 1
        if frame.get("id_locked", False):
            id_locked_count += 1

        people = frame.get("people", [])
        g_data = c_data = None
        for p in people:
            if p.get("role") == "GUARDIAN":
                g_data = p
            elif p.get("role") == "CHILD":
                c_data = p

        if g_data:
            if g_data.get("is_looking", False):
                g_looking += 1
            g_scores.append(g_data.get("looking_score", 0))
            g_confs.append(g_data.get("gaze_confidence", 0))
            g_fit_scores.append(g_data.get("role_fit_score", 0))
            g_det_confs.append(g_data.get("detection_confidence", 0))
            g_human_scores.append(g_data.get("human_score", 0))
            posture = g_data.get("posture", {})
            if "shoulder_tilt_degrees" in posture:
                shoulder_tilts_g.append(posture["shoulder_tilt_degrees"])
            if "torso_height_px" in posture:
                torso_heights_g.append(posture["torso_height_px"])
            if "hand_distance_px" in posture:
                hand_distances_g.append(posture["hand_distance_px"])

        if c_data:
            if c_data.get("is_looking", False):
                c_looking += 1
            c_scores.append(c_data.get("looking_score", 0))
            c_confs.append(c_data.get("gaze_confidence", 0))
            c_fit_scores.append(c_data.get("role_fit_score", 0))
            c_det_confs.append(c_data.get("detection_confidence", 0))
            c_human_scores.append(c_data.get("human_score", 0))
            posture = c_data.get("posture", {})
            if "shoulder_tilt_degrees" in posture:
                shoulder_tilts_c.append(posture["shoulder_tilt_degrees"])
            if "torso_height_px" in posture:
                torso_heights_c.append(posture["torso_height_px"])
            if "hand_distance_px" in posture:
                hand_distances_c.append(posture["hand_distance_px"])

        if g_data and c_data:
            g_head = g_data.get("pos_head", [0, 0])
            c_head = c_data.get("pos_head", [0, 0])
            dist = np.sqrt((g_head[0] - c_head[0]) ** 2 + (g_head[1] - c_head[1]) ** 2)
            head_distances.append(dist)

    last_ts = frames[-1].get("timestamp_s", 0)
    first_ts = frames[0].get("timestamp_s", 0)

    def _s(arr):
        return {"mean": round(float(np.mean(arr)), 3), "std": round(float(np.std(arr)), 3)} if arr else {"mean": 0, "std": 0}

    return {
        "total_frames": total,
        "g_looking_pct": round(100 * g_looking / max(total, 1), 1),
        "c_looking_pct": round(100 * c_looking / max(total, 1), 1),
        "mutual_pct": round(100 * mutual / max(total, 1), 1),
        "id_locked_pct": round(100 * id_locked_count / max(total, 1), 1),
        "duration_s": round(last_ts - first_ts, 1),
        "g_looking_score": _s(g_scores),
        "c_looking_score": _s(c_scores),
        "g_gaze_conf": _s(g_confs),
        "c_gaze_conf": _s(c_confs),
        "g_fit": _s(g_fit_scores),
        "c_fit": _s(c_fit_scores),
        "g_det_conf": _s(g_det_confs),
        "c_det_conf": _s(c_det_confs),
        "g_human_score": _s(g_human_scores),
        "c_human_score": _s(c_human_scores),
        "head_dist": _s(head_distances),
        "shoulder_tilt_g": _s(np.abs(shoulder_tilts_g).tolist() if shoulder_tilts_g else []),
        "shoulder_tilt_c": _s(np.abs(shoulder_tilts_c).tolist() if shoulder_tilts_c else []),
        "torso_g": _s(torso_heights_g),
        "torso_c": _s(torso_heights_c),
        "hand_dist_g": _s(hand_distances_g),
        "hand_dist_c": _s(hand_distances_c),
    }


@st.cache_data(ttl=300)
def build_full_timeline(json_path: str, window: int = 90) -> pd.DataFrame:
    frames = load_json_data(json_path)
    if not frames:
        return pd.DataFrame()

    records = []
    for f in frames:
        people = {p["role"]: p for p in f.get("people", [])}
        g = people.get("GUARDIAN", {})
        c = people.get("CHILD", {})
        g_posture = g.get("posture", {})
        c_posture = c.get("posture", {})
        g_head = g.get("pos_head", [None, None])
        c_head = c.get("pos_head", [None, None])

        head_dist = None
        if g_head[0] is not None and c_head[0] is not None:
            head_dist = np.sqrt((g_head[0] - c_head[0]) ** 2 + (g_head[1] - c_head[1]) ** 2)

        records.append({
            "timestamp_s": f.get("timestamp_s", 0),
            "frame_id": f.get("frame_id", 0),
            "id_locked": 1 if f.get("id_locked", False) else 0,
            "mutual": 1 if f.get("mutual_attention", False) else 0,
            "g_looking": 1 if g.get("is_looking", False) else 0,
            "g_score": g.get("looking_score", 0),
            "g_gaze_conf": g.get("gaze_confidence", 0),
            "g_det_conf": g.get("detection_confidence", 0),
            "g_human_score": g.get("human_score", 0),
            "g_fit_score": g.get("role_fit_score", 0),
            "g_shoulder_tilt": abs(g_posture.get("shoulder_tilt_degrees", 0)),
            "g_torso_height": g_posture.get("torso_height_px", 0),
            "g_hand_dist": g_posture.get("hand_distance_px", 0),
            "c_looking": 1 if c.get("is_looking", False) else 0,
            "c_score": c.get("looking_score", 0),
            "c_gaze_conf": c.get("gaze_confidence", 0),
            "c_det_conf": c.get("detection_confidence", 0),
            "c_human_score": c.get("human_score", 0),
            "c_fit_score": c.get("role_fit_score", 0),
            "c_shoulder_tilt": abs(c_posture.get("shoulder_tilt_degrees", 0)),
            "c_torso_height": c_posture.get("torso_height_px", 0),
            "c_hand_dist": c_posture.get("hand_distance_px", 0),
            "head_distance": head_dist if head_dist else 0,
        })

    df = pd.DataFrame(records)
    if df.empty:
        return df

    for col in ["g_looking", "c_looking", "mutual"]:
        df[f"{col}_roll"] = df[col].rolling(window=window, min_periods=1).mean() * 100

    for col in ["g_score", "c_score", "g_gaze_conf", "c_gaze_conf",
                "g_det_conf", "c_det_conf", "g_human_score", "c_human_score",
                "g_fit_score", "c_fit_score", "head_distance",
                "g_shoulder_tilt", "c_shoulder_tilt", "g_hand_dist", "c_hand_dist",
                "g_torso_height", "c_torso_height"]:
        df[f"{col}_roll"] = df[col].rolling(window=window, min_periods=1).mean()

    return df


@st.cache_data(ttl=300)
def get_keypoint_stats(json_path: str) -> pd.DataFrame:
    frames = load_json_data(json_path)
    if not frames:
        return pd.DataFrame()

    kp_confs_g = {}
    kp_confs_c = {}

    for f in frames:
        for p in f.get("people", []):
            role = p.get("role")
            target = kp_confs_g if role == "GUARDIAN" else kp_confs_c if role == "CHILD" else None
            if target is None:
                continue
            for kp in p.get("keypoints", []):
                name = kp.get("name", "unknown")
                conf = kp.get("conf", 0)
                if name not in target:
                    target[name] = []
                target[name].append(conf)

    rows = []
    all_names = sorted(set(list(kp_confs_g.keys()) + list(kp_confs_c.keys())))
    for name in all_names:
        g_vals = kp_confs_g.get(name, [])
        c_vals = kp_confs_c.get(name, [])
        rows.append({
            "Keypoint": name,
            "Guardian Conf": round(float(np.mean(g_vals)), 3) if g_vals else 0,
            "Child Conf": round(float(np.mean(c_vals)), 3) if c_vals else 0,
        })
    return pd.DataFrame(rows)


