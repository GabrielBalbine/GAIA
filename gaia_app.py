def get_plotly_layout():
    th = theme()
    return dict(
        font=dict(family="Inter, sans-serif", size=12, color=th["text"]),
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor=th["plot_bg"],
        margin=dict(l=55, r=25, t=60, b=55),
        hovermode="x unified",
        legend=dict(
            orientation="h", yanchor="bottom", y=1.05, xanchor="right", x=1,
            font=dict(size=11, color=th["text"]),
        ),
        xaxis=dict(gridcolor=th["plot_grid"], zerolinecolor=th["border"]),
        yaxis=dict(gridcolor=th["plot_grid"], zerolinecolor=th["border"]),
        transition=dict(duration=600, easing="cubic-in-out"),
    )


def styled_fig(fig, **overrides):
    th = theme()
    layout = {**get_plotly_layout(), **overrides}
    for axis_key in ("xaxis", "yaxis"):
        if axis_key in layout:
            ax = layout[axis_key]
            if isinstance(ax, dict):
                ax.setdefault("gridcolor", th["plot_grid"])
                ax.setdefault("zerolinecolor", th["border"])
    fig.update_layout(**layout)
    return fig


