@st.cache_data(ttl=120, max_entries=50)
def extract_video_frame(video_path: str, frame_idx: int) -> bytes | None:
    """Extract a specific frame from video as JPEG bytes using OpenCV."""
    if not CV2_AVAILABLE:
        return None
    try:
        cap = cv2.VideoCapture(video_path)
        cap.set(cv2.CAP_PROP_POS_FRAMES, frame_idx)
        ret, frame = cap.read()
        cap.release()
        if ret:
            _, buffer = cv2.imencode('.jpg', frame, [cv2.IMWRITE_JPEG_QUALITY, 92])
            return buffer.tobytes()
    except Exception:
        pass
    return None


def run_pipeline_with_progress(status_container) -> bool:
    """Run tcc.py as subprocess with real-time progress bar.
    Parses stdout for frame progress and updates st.progress_bar.
    Returns True if pipeline completed successfully.
    """
    progress_bar = status_container.progress(0, text="Iniciando pipeline...")
    log_area = status_container.empty()

    total_frames = 0
    current_frame = 0
    last_log = ""

    try:
        proc = subprocess.Popen(
            [sys.executable, "-u", str(BASE_DIR / "tcc.py")],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            cwd=str(BASE_DIR),
            bufsize=1,
            encoding="utf-8",
            errors="replace",
        )

        for line in proc.stdout:
            line = line.rstrip()
            if not line:
                continue

            # Parse total frames: ">>> Video: 1920x1080 @ 30fps, 52341 frames"
            m_total = re.search(r'(\d+)\s*frames\s*$', line)
            if m_total and "Video" in line:
                total_frames = int(m_total.group(1))

            # Parse tqdm-style progress: "GAIA:  45%|####      | 12345/27000"
            m_tqdm = re.search(r'(\d+)/(\d+)', line)
            if m_tqdm and ("GAIA" in line or "%" in line):
                current_frame = int(m_tqdm.group(1))
                if int(m_tqdm.group(2)) > 0:
                    total_frames = int(m_tqdm.group(2))

            # Parse fallback progress: "  Frame 1200/27000"
            m_fallback = re.search(r'Frame\s+(\d+)/(\d+)', line)
            if m_fallback:
                current_frame = int(m_fallback.group(1))
                total_frames = int(m_fallback.group(2))

            # Parse prescan: "Sampled X frames"
            m_prescan = re.search(r'Sampled\s+(\d+)\s+frames', line)
            if m_prescan:
                last_log = f"Prescan: {m_prescan.group(1)} frames amostrados"
                log_area.caption(last_log)

            # Update progress bar
            if total_frames > 0 and current_frame > 0:
                pct = min(current_frame / total_frames, 1.0)
                progress_bar.progress(
                    pct,
                    text=f"Frame {current_frame:,} / {total_frames:,}  ({pct*100:.1f}%)"
                )
            elif "Processing:" in line:
                # Show which video is being processed
                vid_name = line.split("Processing:")[-1].strip()
                log_area.caption(f"Processando: {vid_name}")
            elif "JSON streaming" in line:
                m_json = re.search(r'(\d+)\s+frames written', line)
                if m_json:
                    progress_bar.progress(1.0, text=f"Concluido — {m_json.group(1)} frames extraidos")
            elif "Marked as processed" in line:
                progress_bar.progress(1.0, text="Video processado com sucesso!")

        proc.wait(timeout=60)
        return proc.returncode == 0

    except Exception as e:
        log_area.error(f"Erro: {e}")
        return False


def get_video_metadata(video_path: str) -> dict | None:
    """Get video metadata using OpenCV."""
    if not CV2_AVAILABLE:
        return None
    try:
        cap = cv2.VideoCapture(video_path)
        meta = {
            "width": int(cap.get(cv2.CAP_PROP_FRAME_WIDTH)),
            "height": int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT)),
            "fps": round(cap.get(cv2.CAP_PROP_FPS), 2),
            "total_frames": int(cap.get(cv2.CAP_PROP_FRAME_COUNT)),
        }
        cap.release()
        meta["duration_s"] = round(meta["total_frames"] / max(meta["fps"], 1), 1)
        return meta
    except Exception:
        return None


