def discover_sessions() -> list:
    sessions = []
    for group in GROUPS:
        json_dir = OUTPUT_DIR / group / "json"
        if not json_dir.exists():
            continue
        for json_file in sorted(json_dir.glob("json_*.json")):
            name = json_file.stem.replace("json_", "")
            video_file = OUTPUT_DIR / group / "video" / f"outputvideo_{name}.mp4"
            report_file = OUTPUT_DIR / group / "relatorio" / f"report_{name}.txt"
            prognosis_file = LSTM_OUTPUT_DIR / "reports" / f"prognostico_{name}.txt"
            sessions.append({
                "name": name,
                "group": group,
                "json_path": str(json_file),
                "video_path": str(video_file) if video_file.exists() else None,
                "report_path": str(report_file) if report_file.exists() else None,
                "has_video": video_file.exists(),
                "has_report": report_file.exists(),
                "has_prognosis": prognosis_file.exists(),
                "prognosis_path": str(prognosis_file) if prognosis_file.exists() else None,
            })
    return sessions


