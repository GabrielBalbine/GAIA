@st.cache_data(ttl=600)
def parse_tea_prob_from_report(report_path: str) -> float | None:
    """Extract P(TEA) value from an existing prognosis report file. Fast text parse."""
    try:
        with open(report_path, "r", encoding="utf-8") as f:
            for line in f:
                m = re.search(r'P\(TEA\)\s*=\s*([\d.]+)%', line)
                if m:
                    return float(m.group(1))
    except Exception:
        pass
    return None


def tea_prob_badge(tea_pct: float) -> str:
    """Return HTML for a small colored P(TEA) badge."""
    if tea_pct > 60:
        bg, fg = "#7f1d1d" if is_dark() else "#fef2f2", C_TEA
    elif tea_pct > 40:
        bg, fg = "#78350f" if is_dark() else "#fffbeb", "#f59e0b"
    else:
        bg, fg = "#064e3b" if is_dark() else "#ecfdf5", C_NT
    return (f'<span style="display:inline-block;padding:2px 8px;border-radius:12px;'
            f'font-size:0.72rem;font-weight:700;font-family:JetBrains Mono,monospace;'
            f'background:{bg};color:{fg};">P(TEA) {tea_pct:.0f}%</span>')


