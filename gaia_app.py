def inject_sounds():
    components.html("""
<script>
(function() {
    const W = window.parent;
    if (W._gaiaAudioReady) return;
    W._gaiaAudioReady = true;

    const AudioCtx = W.AudioContext || W.webkitAudioContext;
    let ctx = null;
    function getCtx() {
        if (!ctx) ctx = new AudioCtx();
        return ctx;
    }

    function playTone(freq, duration, type, vol) {
        try {
            const c = getCtx();
            const osc = c.createOscillator();
            const gain = c.createGain();
            osc.type = type || 'sine';
            osc.frequency.setValueAtTime(freq, c.currentTime);
            gain.gain.setValueAtTime(vol || 0.08, c.currentTime);
            gain.gain.exponentialRampToValueAtTime(0.001, c.currentTime + duration);
            osc.connect(gain);
            gain.connect(c.destination);
            osc.start();
            osc.stop(c.currentTime + duration);
        } catch(e) {}
    }

    W._gaiaChime = function() {
        playTone(880, 0.12, 'sine', 0.07);
        setTimeout(function(){ playTone(1175, 0.18, 'sine', 0.06); }, 80);
    };
    W._gaiaClick = function() {
        playTone(600, 0.06, 'triangle', 0.05);
    };
    W._gaiaPop = function() {
        playTone(520, 0.08, 'sine', 0.05);
        setTimeout(function(){ playTone(780, 0.10, 'sine', 0.04); }, 50);
    };

    function attachSounds() {
        W.document.querySelectorAll('button:not([data-gs])').forEach(function(btn) {
            btn.setAttribute('data-gs', '1');
            btn.addEventListener('mousedown', function() { W._gaiaClick(); });
        });
        W.document.querySelectorAll('[role="tab"]:not([data-gt])').forEach(function(tab) {
            tab.setAttribute('data-gt', '1');
            tab.addEventListener('click', function() { W._gaiaPop(); });
        });
    }

    const obs = new W.MutationObserver(function() { attachSounds(); });
    obs.observe(W.document.body, { childList: true, subtree: true });
    attachSounds();
})();
</script>
""", height=0)


